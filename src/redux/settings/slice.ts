// Packages
import moment from 'moment';
import { createSelector, createSlice } from '@reduxjs/toolkit';

// Thunks
import { getFaqCategoriesAction, getFaqQuestionsAction, submitMessageAction } from './thunks';

// Interfaces
import { RootState } from '@app/store';
import { SettingsInitialState } from './types';

const initialState: SettingsInitialState = {
  faq: [],
  error: null,
  loading: false,
  faqCategories: [],
  lastRefresh: null,
  privacyPolicy: '',
  termsAndConditions: '',
  faqCategoriesLoading: false
};

const settingsSlice = createSlice({
  name: 'settings',
  initialState,
  reducers: {},
  extraReducers: (builder) => {
    builder.addCase(getFaqCategoriesAction.pending, (state) => {
      state.faqCategories = [];
      state.faqCategoriesLoading = true;
      state.error = null;
    });

    builder.addCase(getFaqCategoriesAction.fulfilled, (state, action) => {
      state.faqCategories = action.payload.result;
      state.lastRefresh = moment();
      state.faqCategoriesLoading = false;
      state.error = null;
    });

    builder.addCase(getFaqCategoriesAction.rejected, (state, action) => {
      state.faqCategories = [];
      state.faqCategoriesLoading = false;
      state.error = action.error.message;
    });

    builder.addCase(getFaqQuestionsAction.pending, (state) => {
      state.faq = [];
      state.loading = true;
      state.error = null;
    });

    builder.addCase(getFaqQuestionsAction.fulfilled, (state, action) => {
      state.faq = action.payload.result;
      state.lastRefresh = moment();
      state.loading = false;
      state.error = null;
    });

    builder.addCase(getFaqQuestionsAction.rejected, (state, action) => {
      state.faq = [];
      state.loading = false;
      state.error = action.error.message;
    });

    builder.addCase(submitMessageAction.pending, (state) => {
      state.loading = true;
      state.error = null;
    });

    builder.addCase(submitMessageAction.fulfilled, (state) => {
      state.loading = false;
      state.error = null;
    });

    builder.addCase(submitMessageAction.rejected, (state, action) => {
      state.loading = false;
      state.error = action.error.message;
    });
  }
});

export const destinationsActions = settingsSlice.actions;

// Export the reducer function generated by createSlice
export default settingsSlice.reducer;

// Selectors

const _settings = (state: RootState) => state.settings;

export const selectFaqQuestions = createSelector(_settings, (data) => data.faq);

export const selectSettingsError = createSelector(_settings, (data) => data?.error);

export const selectSettingsLoading = createSelector(_settings, (data) => data?.loading);

export const selectFaqCategories = createSelector(_settings, (data) => data.faqCategories);

export const selectFaqCategoriesLoading = createSelector(_settings, (data) => data?.faqCategoriesLoading);
