// Packages
import moment from 'moment';
import { createSelector, createSlice } from '@reduxjs/toolkit';

// Thunks
import {
  getPopularDestinationsAction,
  getDestinationDetailsAction,
  getTravelersAction,
  getInterestsAction,
  getBudgetsAction
} from './thunks';

// Interfaces
import { RootState } from '@app/store';
import { DestinationInitialState } from './types';

const initialState: DestinationInitialState = {
  error: null,
  details: null,
  budgets: null,
  travelers: null,
  interests: null,
  isLoading: false,
  lastRefresh: null,
  destinations: null,
  loadingOptions: false,
  popularDestinations: null
};

const destinationsSlice = createSlice({
  name: 'destination',
  initialState,
  reducers: {},
  extraReducers: (builder) => {
    builder.addCase(getPopularDestinationsAction.pending, (state) => {
      state.popularDestinations = null;
      state.isLoading = true;
      state.error = null;
    });

    builder.addCase(getPopularDestinationsAction.fulfilled, (state, action) => {
      state.popularDestinations = action.payload.result;
      state.lastRefresh = moment();
      state.isLoading = false;
      state.error = null;
    });

    builder.addCase(getPopularDestinationsAction.rejected, (state, action) => {
      state.popularDestinations = null;
      state.isLoading = false;
      state.error = action.error.message;
    });

    builder.addCase(getDestinationDetailsAction.pending, (state) => {
      state.details = null;
      state.isLoading = true;
      state.error = null;
    });

    builder.addCase(getDestinationDetailsAction.fulfilled, (state, action) => {
      state.details = action.payload.result;
      state.lastRefresh = moment();
      state.isLoading = false;
      state.error = null;
    });

    builder.addCase(getDestinationDetailsAction.rejected, (state, action) => {
      state.details = null;
      state.isLoading = false;
      state.error = action.error.message;
    });

    builder.addCase(getTravelersAction.pending, (state) => {
      state.travelers = null;
      state.loadingOptions = true;
      state.error = null;
    });

    builder.addCase(getTravelersAction.fulfilled, (state, action) => {
      state.travelers = action.payload.result;
      state.loadingOptions = false;
      state.error = null;
    });

    builder.addCase(getTravelersAction.rejected, (state, action) => {
      state.travelers = null;
      state.loadingOptions = false;
      state.error = action.error.message;
    });

    builder.addCase(getInterestsAction.pending, (state) => {
      state.interests = null;
      state.loadingOptions = true;
      state.error = null;
    });

    builder.addCase(getInterestsAction.fulfilled, (state, action) => {
      state.interests = action.payload.result;
      state.loadingOptions = false;
      state.error = null;
    });

    builder.addCase(getInterestsAction.rejected, (state, action) => {
      state.interests = null;
      state.loadingOptions = false;
      state.error = action.error.message;
    });

    builder.addCase(getBudgetsAction.pending, (state) => {
      state.budgets = null;
      state.loadingOptions = true;
      state.error = null;
    });

    builder.addCase(getBudgetsAction.fulfilled, (state, action) => {
      state.budgets = action.payload.result;
      state.loadingOptions = false;
      state.error = null;
    });

    builder.addCase(getBudgetsAction.rejected, (state, action) => {
      state.budgets = null;
      state.loadingOptions = false;
      state.error = action.error.message;
    });
  }
});

export const destinationsActions = destinationsSlice.actions;

// Export the reducer function generated by createSlice
export default destinationsSlice.reducer;

// Selectors
const _destinations = (state: RootState) => state.destination;

export const selectDestinations = createSelector(_destinations, (data) => data);

export const selectBudgetsList = createSelector(_destinations, (data) => data?.budgets);

export const selectInterestsList = createSelector(_destinations, (data) => data?.interests);

export const selectTravelersList = createSelector(_destinations, (data) => data?.travelers);

export const getDestinationDetails = createSelector(_destinations, (data) => data?.details);

export const selectOptionsLoading = createSelector(_destinations, (data) => data?.loadingOptions);

export const getDestinationsLastRefresh = createSelector(_destinations, (data) => data?.lastRefresh);

export const selectPopularDestinations = createSelector(_destinations, (data) => data?.popularDestinations);
